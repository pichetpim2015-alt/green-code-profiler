"""
================================================================================
AI-PerfBench  —  Visual Web Dashboard
================================================================================
Standalone Flask app that reads the JSON report produced by perf_bench.py and
renders a full dark-mode, neon-accented benchmark dashboard.

Usage:
    pip install flask
    python app.py                          # looks for results.json by default
    python app.py --report my_bench.json   # custom path
    python app.py --report results.json --port 8080

Then open:  http://localhost:5000
================================================================================
"""


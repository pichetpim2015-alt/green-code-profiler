app = Flask(__name__)

# ---------------------------------------------------------------------------
# Data loader
# ---------------------------------------------------------------------------

def load_report() -> dict:
    if not REPORT_PATH.exists():
        abort(404, description=f"Report file not found: {REPORT_PATH.resolve()}")
    with open(REPORT_PATH, "r") as f:
        return json.load(f)


